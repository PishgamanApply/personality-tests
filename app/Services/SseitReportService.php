    /**
     * تولید گزارش جامع و تفصیلی نتیجه آزمون شاته.
     *
     * @param  int  $totalScore  نمره کل کسب‌شده (۳۳ تا ۱۶۵)
     * @param  array<string, int>  $subscaleScores  نمرات کسب‌شده در ۴ خرده‌مقیاس
     * @param  string  $primaryType  کد سطح هوش هیجانی (VERY_HIGH_EI, HIGH_EI, ...)
     * @param  bool  $isTimedOut  آیا آزمون با پایان زمان بسته شده؟
     * @param  int  $totalQuestions  تعداد کل سوالات (۳۳)
     * @param  int  $answeredCount  تعداد سوالات پاسخ داده شده
     * @return array<string, mixed>
     */
    public function generate(
        int $totalScore,
        array $subscaleScores,
        string $primaryType,
        bool $isTimedOut,
        int $totalQuestions,
        int $answeredCount
    ): array {
        $maxPossibleScore = 165;
        $minPossibleScore = 33;

        $overallPercentage = (int) round(($totalScore / $maxPossibleScore) * 100);

        // تحلیل تفصیلی هر خرده‌مقیاس
        $subscalesReport = [];
        foreach ($this->subscalesMeta as $key => $meta) {
            $score = (int) ($subscaleScores[$key] ?? 0);
            $maxScore = $meta['max_score'];
            $pct = $maxScore > 0 ? (int) round(($score / $maxScore) * 100) : 0;

            $levelLabel = match (true) {
                $pct >= 80 => 'بسیار بالا',
                $pct >= 70 => 'بالا',
                $pct >= 55 => 'متوسط',
                default => 'نیازمند بهبود',
            };

            $subscalesReport[$key] = [
                'name' => $meta['name'],
                'english_name' => $meta['english_name'],
                'score' => $score,
                'max_score' => $maxScore,
                'percentage' => $pct,
                'level' => $levelLabel,
                'description' => $meta['description'],
                'tips' => $meta['tips'],
            ];
        }

        $profile = $this->levelProfiles[$primaryType] ?? $this->levelProfiles['MODERATE_EI'];

        $limitations = $this->standardLimitations;
        if ($isTimedOut && $answeredCount < $totalQuestions) {
            array_unshift(
                $limitations,
                "این آزمون به دلیل اتمام زمان بسته شده و تنها {$answeredCount} سؤال از مجموع {$totalQuestions} سؤال پاسخ داده شده است؛ لذا نتایج به صورت تخمینی گزارش شده است."
            );
        }

        return [
            'title' => 'گزارش تحلیل و تفسیر هوش هیجانی شاته (SSEIT)',
            'assessment_name' => 'آزمون هوش هیجانی شاته (Schutte Self-Report Emotional Intelligence Test - SSEIT / EIS)',
            'primary_type' => $primaryType,
            'type_title' => $profile['title'],
            'summary' => $profile['summary'],
            'total_score' => $totalScore,
            'min_score' => $minPossibleScore,
            'max_score' => $maxPossibleScore,
            'percentage' => $overallPercentage,
            'level' => match ($primaryType) {
                'VERY_HIGH_EI' => 'بسیار بالا',
                'HIGH_EI' => 'بالا',
                'MODERATE_EI' => 'متوسط',
                default => 'نیازمند بهبود',
            },
            'subscales' => $subscalesReport,
            'traits' => $profile['traits'],
            'strengths' => $profile['strengths'],
            'growth_areas' => $profile['growth_areas'],
            'work_environment' => $profile['work_environment'],
            'is_incomplete' => $isTimedOut && $answeredCount < $totalQuestions,
            'total_questions' => $totalQuestions,
            'answered_count' => $answeredCount,
            'limitations' => $limitations,
        ];
    }
