    /**
     * تولید گزارش کامل نتایج آزمون MBTI
     */
    public function generate(
        array $scores,
        ?string $primaryType,
        array $dichotomies,
        bool $isTimedOut,
        int $totalQuestions,
        int $answeredCount
    ): array {
        $profile = $this->typeProfiles[$primaryType] ?? $this->typeProfiles['INTJ'];

        $dichotomiesReport = [];
        foreach ($this->dichotomiesMeta as $key => $meta) {
            $data = $dichotomies[$key] ?? [
                'preference' => $key[0],
                'percentage' => 50,
                'left_score' => 0,
                'right_score' => 0,
            ];

            $prefCode = $data['preference'];
            $prefInfo = ($prefCode === $meta['left']['code']) ? $meta['left'] : $meta['right'];

            $dichotomiesReport[$key] = [
                'name' => $meta['name'],
                'preference' => $prefCode,
                'preference_name' => $prefInfo['name'],
                'description' => $prefInfo['desc'],
                'percentage' => $data['percentage'],
                'left_code' => $meta['left']['code'],
                'left_score' => $data['left_score'],
                'right_code' => $meta['right']['code'],
                'right_score' => $data['right_score'],
            ];
        }

        $limitations = [
            'تیپ شخصیتی MBTI نمایانگر ترجیحات ذاتی و الگوهای رفتاری عمومی است و به معنای محدودیت توانایی‌های فردی نیست.',
            'انسان‌ها در طول زمان و با کسب تجربه می‌توانند کارکردهای متضاد تیپ خود را نیز به خوبی پرورش دهند.',
        ];

        if ($isTimedOut && $answeredCount < $totalQuestions) {
            array_unshift(
                $limitations,
                "این آزمون به دلیل اتمام زمان به پایان رسیده و تنها {$answeredCount} سؤال از مجموع {$totalQuestions} سؤال پاسخ داده شده است؛ لذا نتایج تخمینی می‌باشد."
            );
        }

        return [
            'title' => 'گزارش تحلیلی تیپ شخصیتی MBTI (بر اساس OEJTS 1.2)',
            'assessment_name' => 'MBTI (Open Extended Jungian Type Scales)',
            'primary_type' => $primaryType,
            'type_title' => $profile['title'],
            'summary' => $profile['summary'],
            'dichotomies' => $dichotomiesReport,
            'traits' => $profile['traits'],
            'strengths' => $profile['strengths'],
            'growth_areas' => $profile['growth_areas'],
            'work_environment' => $profile['work_environment'],
            'is_incomplete' => $isTimedOut && $answeredCount < $totalQuestions,
            'total_questions' => $totalQuestions,
            'answered_count' => $answeredCount,
            'limitations' => $limitations,
        ];
    }
