            'growth_areas' => ['برنامه‌ریزی بلندمدت و آینده‌نگری', 'مدیریت تعهدات مالی و کاری', 'پرهیز از فرار از گفتگوهای جدی'],
            'work_environment' => 'محیط‌های رویدادمحور، رسانه‌ای، گردشگری، هنری و خدمات رفاهی پویا.',
