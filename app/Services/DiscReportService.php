    /**
     * تولید گزارش کامل و خوانا
     */
    public function generate(
        array $scores,
        ?string $primaryType,
        array $topDimensions,
        bool $isTimedOut,
        int $totalQuestions,
        int $answeredCount
    ): array {
        $dimensionsReport = [];
        $maxDimensionScore = 20; // 4 سؤال برای هر بُعد ضرب در سقف ۵ نمره

        foreach ($this->dimensionsMeta as $key => $meta) {
            $score = (int) ($scores[$key] ?? 0);
            $percentage = $maxDimensionScore > 0
                ? (int) round(($score / $maxDimensionScore) * 100)
                : 0;

            $level = match (true) {
                $percentage >= 75 => 'بالا',
                $percentage >= 50 => 'متوسط به بالا',
                $percentage >= 25 => 'متوسط به پایین',
                default => 'پایین',
            };

            $dimensionsReport[$key] = [
                'name' => $meta['name'],
                'english_name' => $meta['english_name'],
                'score' => $score,
                'max_score' => $maxDimensionScore,
                'percentage' => $percentage,
                'level' => $level,
                'description' => $meta['description'],
            ];
        }

        $isTie = count($topDimensions) > 1 && count($topDimensions) < 4;
        $isUniform = count($topDimensions) === 4 || max($scores) === 0;

        if ($isUniform || ! $primaryType) {
            $typeTitle = 'پروفایل متوازن یا ارزیابی ناقص';
            $summary = $isTimedOut && $answeredCount < $totalQuestions
                ? 'مهلت زمان آزمون به پایان رسیده و تعداد پاسخ‌های ثبت‌شده برای تعیین قطعی تیپ رفتاری غالب کافی نبوده است.'
                : 'نمرات شما در ابعاد چهارگانه رفتاری بسیار به هم نزدیک و متوازن است و هیچ بعد رفتاری به تنهایی بر سایر ابعاد غلبه ندارد.';
            $traits = [
                'انعطاف‌پذیری رفتاری و انطباق متناسب با شرایط گوناگون',
                'عدم وابستگی شدید به یک سبک رفتاری ثابت و مشخص',
            ];
            $strengths = [
                'قابلیت همراهی با گروه‌ها و سبک‌های مختلف کاری',
                'ایفای نقش میانجی در موقعیت‌های تعارض رفتاری',
            ];
            $growth_areas = [
                'تمرکز و تقویت جنبه‌های رفتاری متناسب با نقش شغلی کنونی',
            ];
            $workEnvironment = 'محیط‌های منعطف با وظایف متغیر و نیاز به رفتارهای انطباق‌پذیر.';
        } elseif ($isTie) {
            $typeTitle = "تیپ ترکیبی {$primaryType} (رفتار چندگانه متعادل)";
            $summary = 'امتیاز شما در ابعاد '.implode(' و ', array_map(fn ($d) => $this->dimensionsMeta[$d]['name'] ?? $d, $topDimensions)).' برابر است. این ویژگی نشان‌دهنده سبک رفتاری ترکیبی و بهره‌گیری هم‌زمان از توانمندی‌های چند بعد می‌باشد.';

            $traits = [];
            $strengths = [];
            $growth_areas = [];

            foreach ($topDimensions as $dim) {
                if (isset($this->singleTypeProfiles[$dim])) {
                    $traits[] = $this->singleTypeProfiles[$dim]['traits'][0];
                    $strengths[] = $this->singleTypeProfiles[$dim]['strengths'][0];
                    $growth_areas[] = $this->singleTypeProfiles[$dim]['growth_areas'][0];
                }
            }

            $workEnvironment = 'محیط‌های کاری متعادل که نیازمند ترکیب سرعت عمل، تعامل، نظم و کیفیت هستند.';
        } else {
            $profile = $this->singleTypeProfiles[$primaryType] ?? $this->singleTypeProfiles['D'];
            $typeTitle = $profile['title'];
            $summary = $profile['summary'];
            $traits = $profile['traits'];
            $strengths = $profile['strengths'];
            $growth_areas = $profile['growth_areas'];
            $workEnvironment = $profile['work_environment'];
        }

        $limitations = $this->standardLimitations;
        if ($isTimedOut && $answeredCount < $totalQuestions) {
            array_unshift(
                $limitations,
                "این آزمون به دلیل اتمام زمان به پایان رسیده و تنها {$answeredCount} سؤال از مجموع {$totalQuestions} سؤال پاسخ داده شده است؛ لذا نتایج تخمینی بوده و به صورت کامل منعکس‌کننده سبک رفتاری شما نیست."
            );
        }

        return [
            'title' => 'گزارش ارزیابی و تفسیر رفتارشناسی DISC',
            'assessment_name' => 'DISC (ODAT 1.0)',
            'primary_type' => $primaryType,
            'type_title' => $typeTitle,
            'summary' => $summary,
            'dimensions' => $dimensionsReport,
            'traits' => $traits,
            'strengths' => $strengths,
            'growth_areas' => $growth_areas,
            'work_environment' => $workEnvironment,
            'is_incomplete' => $isTimedOut && $answeredCount < $totalQuestions,
            'total_questions' => $totalQuestions,
            'answered_count' => $answeredCount,
            'limitations' => $limitations,
        ];
    }
